-- QTEs: game-wide quick-time events, broadcast to every player; belongs to
-- qte. One row per QTE, run at most once. Status is derived, never stored:
-- draft (started_at NULL), open (now before ends_at), closed.
--   kind            what it is: 'quiz' only, for now; each kind has its own
--                   columns, checked by its own CHECK
--   powerup         what a correct answer earns (teamstate's powerup kinds)
--   question        quiz: the question
--   options         quiz: the choices, in order (answers name one by index)
--   correct_option  quiz: the index of the right choice
--   window_s        how long it stays open once started; NULL: config.toml's
--                   qte.answer_window at the start
--   created_by      the admin who wrote it; NULL for a seeded one
--   started_at      when it was started; NULL while a draft
--   ends_at         when answers stop: started_at + its window, or earlier
--                   if an admin ended it
CREATE TABLE qte (
    id             BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind           TEXT        NOT NULL CHECK (kind IN ('quiz')),
    powerup        TEXT        NOT NULL CHECK (powerup IN ('damage_multiplier', 'heart', 'short_qr_cooldown', 'instant_cast')),
    question       TEXT        NULL,
    options        TEXT[]      NULL,
    correct_option INTEGER     NULL,
    window_s       INTEGER     NULL CHECK (window_s > 0),
    created_by     UUID        NULL REFERENCES userprofile (id) ON DELETE SET NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    started_at     TIMESTAMPTZ NULL,
    ends_at        TIMESTAMPTZ NULL,
    CHECK ((started_at IS NULL) = (ends_at IS NULL)),
    CHECK (ends_at >= started_at),
    -- a quiz has a question, at least two non-null options, and a right one
    CHECK (kind <> 'quiz' OR (question <> '' AND cardinality(options) >= 2
        AND array_position(options, NULL) IS NULL
        AND correct_option >= 0 AND correct_option < cardinality(options))),
    -- one QTE at a time: no two runs overlap
    EXCLUDE USING gist (tstzrange(started_at, ends_at, '[)') WITH &&) WHERE (started_at IS NOT NULL)
);

-- A team's answer to a QTE; belongs to teamstate. The primary key is the rule:
-- one answer per team per QTE.
--   option       the index it chose
--   correct      it was the right one
--   granted      the team got the QTE's powerup (false when wrong, or when it
--                already held that kind, so the reward was wasted)
--   answered_by  the member who answered for the team
CREATE TABLE team_qte_answer (
    team_id     VARCHAR(6)  NOT NULL REFERENCES team (id) ON DELETE CASCADE,
    qte_id      BIGINT      NOT NULL REFERENCES qte (id),
    option      INTEGER     NOT NULL CHECK (option >= 0),
    correct     BOOLEAN     NOT NULL,
    granted     BOOLEAN     NOT NULL,
    answered_by UUID        NOT NULL REFERENCES userprofile (id),
    answered_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (team_id, qte_id),
    CHECK (correct OR NOT granted)
);
